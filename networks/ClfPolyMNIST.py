import torch.nn as nn
import torch.nn.functional as F
import numpy as np

from networks.PolyMNIST import ResnetBlock, actvn


class ClfImgPolyMNIST(nn.Module):
    def __init__(self):  # , z_dim, size, nfilter=64, nfilter_max=1024, **kwargs):
        super().__init__()
        s0 = self.s0 = 7  # kwargs['s0']
        nf = self.nf = 64  # nfilter
        nf_max = self.nf_max = 1024  # nfilter_max
        size = 28

        # Submodules
        nlayers = int(np.log2(size / s0))
        self.nf0 = min(nf_max, nf * 2**nlayers)

        blocks = [
            ResnetBlock(nf, nf)
        ]

        for i in range(nlayers):
            nf0 = min(nf * 2**i, nf_max)
            nf1 = min(nf * 2**(i+1), nf_max)
            blocks += [
                nn.AvgPool2d(3, stride=2, padding=1),
                ResnetBlock(nf0, nf1),
            ]

        self.conv_img = nn.Conv2d(3, 1*nf, 3, padding=1)
        self.resnet = nn.Sequential(*blocks)
        self.fc = nn.Linear(self.nf0*s0*s0, 10)

    def forward(self, x):
        batch_size = x.size(0)
        out = self.conv_img(x)
        out = self.resnet(out)
        out = out.reshape(batch_size, self.nf0*self.s0*self.s0)
        return self.fc(actvn(out))
        # return F.log_softmax(out, dim=-1)
        return out